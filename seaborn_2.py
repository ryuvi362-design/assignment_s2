import pandas as pd
import seaborn as sns
import matplotlib.pyplot as plt
df = pd.DataFrame({
    'Payment': ['UPI', 'Card', 'Cash', 'UPI', 'UPI',
                'Card', 'Cash', 'UPI', 'Card', 'Cash']
})

sns.countplot(data=df, x='Payment')
plt.title('Number of Orders by Payment Method')
plt.xlabel('Payment Method')
plt.ylabel('Number of Orders')
plt.show()

df = pd.DataFrame({
    'Category': ['Pizza', 'Pizza', 'Burger', 'Burger',
                 'Biryani', 'Biryani', 'South Indian', 'South Indian'],
    'DeliveryTime': [30, 40, 20, 30, 35, 45, 25, 35]
})

sns.barplot(data=df, x='Category', y='DeliveryTime',
            estimator='mean', errorbar=None)

plt.title('Average Delivery Time by Food Category')
plt.xlabel('Food Category')
plt.ylabel('Average Delivery Time (minutes)')
plt.xticks(rotation=15)
plt.show()

df = pd.DataFrame({
    'Category': ['Pizza', 'Pizza', 'Burger', 'Burger',
                 'Biryani', 'Biryani', 'South Indian', 'South Indian'],
    'Orders': [1, 1, 1, 1, 1, 1, 1, 1]
})

# Show total orders for each category
sns.barplot(data=df, x='Category', y='Orders',
            estimator='sum', errorbar=None)

plt.title('Total Orders by Food Category')
plt.xlabel('Food Category')
plt.ylabel('Total Orders')
plt.xticks(rotation=15)
plt.show()

